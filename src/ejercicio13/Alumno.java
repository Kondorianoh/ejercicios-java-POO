package ejercicio13;

public class Alumno {
	
	private String nombre;
	private String legajo;
	
	public Alumno(String nombre, String legajo) {
		this.nombre = nombre;
		this.legajo = legajo;
	}
	
	public String getNombre() {
		return this.nombre;
	}
	
	public String getLegajo() {
		return this.legajo;
	}

}
